  /* ---------------- 工具 ---------------- */
  var TYPES = ['cold', 'warm', 'stationary', 'general'];

  function isType(t) {
    for (var i = 0; i < TYPES.length; i++) if (TYPES[i] === t) return true;
    return false;
  }

  function shuffle(arr) {
    for (var i = arr.length - 1; i > 0; i--) {
      var j = Math.floor(Math.random() * (i + 1));
      var tmp = arr[i];
      arr[i] = arr[j];
      arr[j] = tmp;
    }
    return arr;
  }

  /* 按类型筛选（供调试/扩展，不影响 pick） */
  function filter(type) {
    var out = [];
    for (var i = 0; i < bank.length; i++) {
      if (!type || type === 'all' || bank[i].type === type) out.push(bank[i]);
    }
    return out;
  }

  /* 抽 n 道：该类型题 ≥ 一半（向上取整），其余由综合题和其他类型补齐，不重复 */
  function pick(type, n) {
    n = Math.round(Number(n));
    if (!(n > 0)) n = 6;
    n = Math.min(n, bank.length);

    var ty = isType(type) ? type : 'general';
    var typed = [], others = [], i;
    for (i = 0; i < bank.length; i++) {
      if (bank[i].type === ty) typed.push(bank[i]);
      else others.push(bank[i]);
    }
    shuffle(typed);
    shuffle(others);

    var need = Math.min(typed.length, Math.ceil(n * 0.6));
    var out = [], seen = {};

    function add(q) {
      if (!q) return false;
      var key = q.q;
      if (seen[key]) return false;
      seen[key] = true;
      out.push(q);
      return true;
    }

    for (i = 0; i < need; i++) add(typed[i]);

    /* 剩余候选：该类型其余题 + 其他类型题，打乱后补齐 */
    var rest = [];
    for (i = need; i < typed.length; i++) rest.push(typed[i]);
    for (i = 0; i < others.length; i++) rest.push(others[i]);
    shuffle(rest);
    for (i = 0; i < rest.length && out.length < n; i++) add(rest[i]);

    shuffle(out);
    return out;
  }

